"""Generate geppetto-client/js/common/xmi/GeppettoModelSchema.js from geppettoModel.ecore.

The client turns vfb.xmi into the model JSON the server used to send, and needs
to know, for every class, which XMI attributes are references (and whether they
are lists), which child elements are contained objects, what type a child with
no xsi:type has, and which attributes the server always wrote out. All of that
is in the ecore; this flattens it (supertypes included) into a small table.

    curl -sSLO https://raw.githubusercontent.com/VirtualFlyBrain/org.geppetto.model/vfb_20200604_a/src/main/resources/geppettoModel.ecore
    python3 scripts/xmi-model/schema.py geppettoModel.ecore > geppetto-client/js/common/xmi/GeppettoModelSchema.js
"""
import json
import sys
import xml.etree.ElementTree as ET

XSI = '{http://www.w3.org/2001/XMLSchema-instance}type'


def scalar(etype):
    name = (etype or '').split('#//')[-1]
    if name in ('Boolean', 'EBoolean', 'EBooleanObject'):
        return 'b'
    if name in ('Int', 'EInt', 'Long', 'ELong', 'EIntegerObject', 'Integer', 'Short'):
        return 'i'
    if name in ('Double', 'EDouble', 'Float', 'EFloat', 'EDoubleObject'):
        return 'f'
    return 's'


def main(path):
    root = ET.parse(path).getroot()
    raw = {}
    entries = set()

    def walk(pkg, prefix):
        for c in pkg.findall('eClassifiers'):
            if c.get(XSI) != 'ecore:EClass':
                continue
            path = prefix + '/' + c.get('name')
            if c.get('instanceClassName') == 'java.util.Map$Entry':
                entries.add(c.get('name'))
            feats = {}
            for f in c.findall('eStructuralFeatures'):
                if f.get('transient') == 'true' or f.get('derived') == 'true':
                    continue
                kind = f.get(XSI).split(':')[1]
                many = f.get('upperBound') == '-1'
                if kind == 'EAttribute':
                    t = scalar(f.get('eType'))
                    feat = {'k': 'a', 't': t}
                    default = f.get('defaultValueLiteral')
                    # The server (EMF JSON) writes a String that defaults to ""
                    # and every boolean even when unset; anything else only
                    # when the XMI sets it.
                    if t == 'b':
                        feat['d'] = default == 'true'
                    elif t == 's' and default == '':
                        feat['d'] = ''
                else:
                    feat = {'k': 'c' if f.get('containment') == 'true' else 'r',
                            't': f.get('eType').split('/')[-1]}
                if many:
                    feat['m'] = 1
                feats[f.get('name')] = feat
            supers = [s.split('/')[-1] for s in (c.get('eSuperTypes') or '').split()]
            raw[c.get('name')] = {'supers': supers, 'feats': feats}
        for sub in pkg.findall('eSubpackages'):
            walk(sub, prefix + '/' + sub.get('name'))

    walk(root, '')

    flat = {}

    def resolve(name):
        if name in flat:
            return flat[name]
        out = {}
        for s in raw[name]['supers']:
            out.update(resolve(s))
        out.update(raw[name]['feats'])
        flat[name] = out
        return out

    for name in raw:
        resolve(name)

    body = json.dumps({'classes': flat, 'mapEntries': sorted(entries)}, indent=1, sort_keys=True)
    sys.stdout.write('/*\n * Generated by scripts/xmi-model/schema.py from geppettoModel.ecore\n'
                     ' * (VirtualFlyBrain/org.geppetto.model, vfb_20200604_a). Do not edit.\n *\n'
                     ' * k: a attribute, r reference, c contained object; t: scalar type\n'
                     ' * (s/b/i/f) or class name; m: many; d: value the server always wrote.\n */\n'
                     'export default ' + body + ';\n')


if __name__ == '__main__':
    main(sys.argv[1])
